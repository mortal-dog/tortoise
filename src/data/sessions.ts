/** The long form (Sunday): "every hold of both blocks done twice"; a hold already done twice stays at 2 sets. */
function longForm(steps: StepInput[]): StepInput[] {
  return steps.map((s) => ({ ...s, id: `long-${s.id}`, sets: 2 }))
}

