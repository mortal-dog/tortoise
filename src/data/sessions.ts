// The sessions (plan §6). Each step's `dose` is the plan's table cell verbatim and `why` its "Why" cell verbatim, with
// the cited ids in `sources`. Where the plan writes more about a step than the dose holds (the exercise cell of a
// strength table, a fallback, a later form), `note` carries the plan's own words. Doses are the plan's own choices,
// so every session carries `ourRule`.
//
// `minutes` is the session's total as a range, warm-up included (design §7):
// - strength days: the 5-min warm-up and about 30 min of work;
// - Tuesday: 5 min of walking, 30–40 min of running and 3 min of walking;
// - Thursday: the 8-min warm-up, about 3 min of squat jumps (our rule: the plan gives no time for them), the main set
//   of the shortest stage (Block 2, 6 × 2 min = 12 min) to the longest (Block 4 on, 4 × 7 min = 28 min) and the 3-min
//   cool-down;
// - Saturday: 5 min of walking, the week table's 45–90 min run and 10 min of rows and farmer holds at home;
// - Sunday: the 30-min flexibility session; the walk before it has no length in the plan and is left out.
// `pillars` share the middle of `minutes` among the four pillars (design §8); the shares are our rule.
