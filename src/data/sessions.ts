/**
 * The long form (Sunday): "every hold of both blocks done twice". A hold is a step timed in seconds; the two
 * rep steps (the active front-leg lift and the side-lying leg raise) keep their 2 × 8.
 */
function longForm(steps: StepInput[]): StepInput[] {
  return steps.map((s) => (s.seconds ? { ...s, id: `long-${s.id}`, sets: 2 } : { ...s, id: `long-${s.id}` }))
}

